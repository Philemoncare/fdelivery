export const SUPPORTED_LANGUAGES: { code: LanguageCode; label: string }[] = [
  { code: 'EN', label: 'English' },
  { code: 'FR', label: 'Français' },
  { code: 'ES', label: 'Español' },
  { code: 'DE', label: 'Deutsch' },
  { code: 'ZH-CN', label: '中文 (简体)' },
  { code: 'AR', label: 'العربية' }
];

const dictionaries: Record<LanguageCode, Dictionary> = { EN: en, FR: fr, ES: es, DE: de, 'ZH-CN': zhCN, AR: ar };

export function translate(language: LanguageCode, key: string, values?: Values): string {
  const template = dictionaries[language]?.[key] ?? en[key] ?? key;
  return template.replace(/{{(\w+)}}/g, (_, name) => String(values?.[name] ?? `{{${name}}}`));
}
